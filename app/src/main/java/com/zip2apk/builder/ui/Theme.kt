@Composable
fun Zip2ApkTheme(
    themeMode: ThemeMode = ThemeMode.SYSTEM,
    materialYou: Boolean = false,
    content: @Composable () -> Unit
) {
    val darkTheme = when (themeMode) {
        ThemeMode.SYSTEM -> isSystemInDarkTheme()
        ThemeMode.LIGHT -> false
        ThemeMode.DARK -> true
    }

    val context = LocalContext.current
    val dynamicColorAvailable = Build.VERSION.SDK_INT >= Build.VERSION_CODES.S

    // These are Android's official Compose Material 3 dynamic-color APIs. On
    // Android 12+ they read the system's current wallpaper/theme-derived color
    // resources, including the color choice made in Wallpaper & style.
    val colorScheme = when {
        materialYou && dynamicColorAvailable && darkTheme -> dynamicDarkColorScheme(context)
        materialYou && dynamicColorAvailable -> dynamicLightColorScheme(context)
        darkTheme -> Zip2ApkDarkColors
        else -> Zip2ApkLightColors
    }

    MaterialTheme(
        colorScheme = colorScheme,
        content = content
    )
}
